const C_MAJOR_DEGREES = ["C", "D", "E", "F", "G", "A", "B"] as const;
const DURATION_BY_CODE: Record<string, SongPracticeDuration> = {
  q: "quarter",
  e: "eighth",
  s: "sixteenth",
  w: "whole",
};

function decodeRows(
  rows: readonly EncodedScoreRow[],
  staff: SongPracticeStaff
): SongPracticeNote[] {
  return rows.flatMap((row) => {
    const lyricLines = new Map<number, Map<number, string>>();
    for (const lyricLine of row.lyrics ?? []) {
      lyricLines.set(
        lyricLine.line,
        new Map(lyricLine.notes.map(({ index, text }) => [index, text]))
      );
    }
    return Array.from(row.pitches, (degree, index) => {
      const lyrics = [...lyricLines.values()].map((line) => line.get(index) ?? "");
      return {
        noteName: C_MAJOR_DEGREES[Number(degree) - 1],
        octave: Number(row.octaves[index]),
        duration: DURATION_BY_CODE[row.durations[index]],
        measure: row.firstMeasure + Number(row.measures[index]) - 1,
        onset: parseInt(row.onsets[index], 36) / 35,
        staff,
        ...(lyrics.some(Boolean) ? { lyrics } : {}),
      };
    });
  });
}

